                    大的往后「冒泡」，可提前退出优化。
                    
                    示例：[5, 3, 8, 4, 2]
                    输出：[2, 3, 4, 5, 8]
                """,
                explanation: """
                    【核心思路】相邻比较 + 冒泡 + 提前退出：
                    
