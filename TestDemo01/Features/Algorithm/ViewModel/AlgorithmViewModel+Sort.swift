import Foundation

extension AlgorithmViewModel {
    
    // MARK: - 题目 017：选择排序（Selection Sort）
    ///
    /// **题意**：实现选择排序算法，将数组按升序排列。
    ///
    /// **算法思路**：
    /// - 将数组分为「已排序区」和「未排序区」
    /// - 每轮从未排序区中找到最小值的下标
    /// - 将最小值与未排序区的第一个元素交换
    /// - 已排序区向右扩展一位
    /// - 重复 n-1 轮完成排序
    ///
    /// **示例**：
    /// - 输入：[64, 25, 12, 22, 11]
    /// - 过程：
    ///   第1轮：[11, 25, 12, 22, 64]（11 和 64 交换）
    ///   第2轮：[11, 12, 25, 22, 64]（12 和 25 交换）
    ///   第3轮：[11, 12, 22, 25, 64]（22 和 25 交换）
    ///   第4轮：[11, 12, 22, 25, 64]（已有序，25 和 25 自身交换）
    ///
    /// **复杂度**：
    /// - 时间 O(n²) —— 无论什么数据都是 O(n²)
    /// - 空间 O(1) —— 原地排序
    /// - **不稳定排序**（交换可能打乱相同元素的相对顺序）
    ///
    /// **面试考点**：与冒泡排序的区别、为什么不稳定
    ///
    static func selectionSort(_ arr: [Int]) -> [Int] {
        var nums = arr
        let n = nums.count
        for i in 0..<(n - 1) {
            var minIndex = i
            for j in (i + 1)..<n {
                if nums[j] < nums[minIndex] {
                    minIndex = j
                }
            }
            if minIndex != i {
                nums.swapAt(i, minIndex)
            }
        }
        return nums
    }
    
    // MARK: - 题目 018：冒泡排序（Bubble Sort）
    ///
    /// **题意**：实现冒泡排序算法，将数组按升序排列。
    ///
    /// **算法思路**：
    /// - 相邻元素两两比较，如果前一个比后一个大就交换
    /// - 每一轮遍历会将当前未排序区的最大值「冒泡」到末尾
    /// - 优化：如果某一轮没有发生任何交换，说明已经有序，可以提前退出
    ///
    /// **示例**：
    /// - 输入：[5, 3, 8, 4, 2]
    /// - 过程：
    ///   第1轮：[3, 5, 4, 2, 8]（8 冒泡到末尾）
    ///   第2轮：[3, 4, 2, 5, 8]（5 冒泡到倒数第二）
    ///   第3轮：[3, 2, 4, 5, 8]（4 冒泡到倒数第三）
    ///   第4轮：[2, 3, 4, 5, 8]（排序完成）
    ///
    /// **复杂度**：
    /// - 最坏/平均时间 O(n²)
    /// - 最好时间 O(n)（已有序 + 优化提前退出）
    /// - 空间 O(1) —— 原地排序
    /// - **稳定排序**（相同元素不会交换，相对顺序不变）
    ///
    /// **面试考点**：优化（提前退出标志位）、稳定性分析、与选择排序的对比
    ///
    static func bubbleSort(_ arr: [Int]) -> [Int] {
        var nums = arr
        let n = nums.count
        for i in 0..<(n - 1) {
            var swapped = false
            for j in 0..<(n - 1 - i) {
                if nums[j] > nums[j + 1] {
                    nums.swapAt(j, j + 1)
                    swapped = true
                }
            }
            if !swapped { break }  // 优化：本轮无交换 → 已有序
        }
        return nums
    }
}

