                    实现选择排序：每轮从未排序区找最小值，
                    与未排序区第一个元素交换。
                    
                    示例：[64, 25, 12, 22, 11]
                    输出：[11, 12, 22, 25, 64]
                """,
                explanation: """
                    【核心思路】找最小值 → 放到前面：
                    
                    1. 外层循环 i 从 0 到 n-2（最后一个自然有序）
                    2. 内层循环从 i+1 到 n-1，找最小值的下标 minIndex
                    3. 如果 minIndex != i，交换 nums[i] 和 nums[minIndex]
                    4. 每轮保证前 i+1 个元素是最终排序结果
                    
                    时间复杂度：O(n²) —— 无论数据分布都是 O(n²)
                    空间复杂度：O(1) —— 原地排序
                    稳定性：不稳定（如 [5, 5, 2]，第一轮两个 5 的相对顺序会变）
                    
                    【选择排序 vs 冒泡排序】
                    - 选择排序：每轮只交换 1 次（找到最小值后交换）
                    - 冒泡排序：每轮可能交换多次（相邻就比就换）
                    - 选择排序的交换次数更少（最多 n-1 次），但比较次数一样
                    - 冒泡是稳定排序，选择是不稳定排序
                    
                    【面试追问：什么时候选选择排序？】
                    实际工程中很少用 O(n²) 排序，但选择排序的优势在于
                    交换次数最少（适合「交换代价大」的场景，如写入 Flash）。
                """,
                solution: {
                    let input = [64, 25, 12, 22, 11]
                    let result = AlgorithmViewModel.selectionSort(input)
                    return """
                        输入：\(input)
                        选择排序后：\(result)
                        
                        排序过程：
                        初始：[64, 25, 12, 22, 11]
                        第1轮找最小 11 → 与 64 交换 → [11, 25, 12, 22, 64]
                        第2轮找最小 12 → 与 25 交换 → [11, 12, 25, 22, 64]
                        第3轮找最小 22 → 与 25 交换 → [11, 12, 22, 25, 64]
                        第4轮 25 和 64 已有序         → [11, 12, 22, 25, 64]
                    """
