                    2. 内层循环 j 从 0 到 n-2-i（每轮末尾已有序，无需再比）
                    3. 如果 nums[j] > nums[j+1]，交换它们
                    4. 用 swapped 标记本轮是否有交换
                    5. 如果本轮没有交换 → 数组已有序 → break 提前退出
                    
                    时间复杂度：
                    - 最好 O(n) —— 已有序，一轮无交换就退出
                    - 最坏/平均 O(n²) —— 逆序
                    空间复杂度：O(1) —— 原地排序
                    稳定性：稳定（只在严格大于时交换，相同元素不会交换）
                    
                    【冒泡排序的三个优化层次】
                    1. 基础优化：swapped 标志提前退出
                    2. 记录最后一次交换位置：缩小下轮比较范围
                    3. 鸡尾酒排序（双向冒泡）：交替正反方向遍历
                    
                    【面试常问对比】
                    | 特性 | 冒泡 | 选择 | 插入 |
